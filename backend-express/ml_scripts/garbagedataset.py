IMG_SIZE_TRAIN = (224, 224)
BATCH_SIZE = 16   # keep at 16, not 32 — this is what makes 224x224 safe

train_ds = tf.keras.utils.image_dataset_from_directory(
    TRAIN_DIR, image_size=IMG_SIZE_TRAIN, batch_size=BATCH_SIZE,
    label_mode="categorical", seed=SEED)
val_ds = tf.keras.utils.image_dataset_from_directory(
    VAL_DIR, image_size=IMG_SIZE_TRAIN, batch_size=BATCH_SIZE,
    label_mode="categorical", seed=SEED)
test_ds = tf.keras.utils.image_dataset_from_directory(
    TEST_DIR, image_size=IMG_SIZE_TRAIN, batch_size=BATCH_SIZE,
    label_mode="categorical", seed=SEED, shuffle=False)

CLASS_NAMES = train_ds.class_names
print(CLASS_NAMES)

data_augmentation = tf.keras.Sequential([
    layers.RandomFlip("horizontal"),
    layers.RandomRotation(0.1),
    layers.RandomZoom(0.1),
    layers.RandomContrast(0.1),
])

AUTOTUNE = tf.data.AUTOTUNE

def prep(ds, training=False, cache_path=None):
    ds = ds.map(lambda x, y: (preprocess_input(x), y), num_parallel_calls=AUTOTUNE)
    if training:
        ds = ds.map(lambda x, y: (data_augmentation(x, training=True), y), num_parallel_calls=AUTOTUNE)
    if cache_path:
        ds = ds.cache(cache_path)  # local Colab disk only — NOT Drive
    return ds.prefetch(buffer_size=2)

os.makedirs("/content/cache", exist_ok=True)
train_ds_p = prep(train_ds, training=True, cache_path="/content/cache/train")
val_ds_p   = prep(val_ds, cache_path="/content/cache/val")
test_ds_p  = prep(test_ds, cache_path="/content/cache/test")

base_model = MobileNetV2(input_shape=IMG_SIZE_TRAIN + (3,), include_top=False, weights="imagenet")
base_model.trainable = False

inputs = tf.keras.Input(shape=IMG_SIZE_TRAIN + (3,))
x = base_model(inputs, training=False)
x = layers.GlobalAveragePooling2D()(x)
x = layers.Dropout(0.3)(x)
x = layers.Dense(128, activation="relu")(x)
x = layers.Dropout(0.2)(x)
outputs = layers.Dense(NUM_CLASSES, activation="softmax")(x)

model = models.Model(inputs, outputs)
model.compile(optimizer=tf.keras.optimizers.Adam(1e-3),
              loss="categorical_crossentropy", metrics=["accuracy"])
model.summary()

MODEL_DIR = "/content/drive/My Drive/Datasets/CitizenPulseAI/models"
os.makedirs(MODEL_DIR, exist_ok=True)

callbacks = [
    EarlyStopping(monitor="val_accuracy", patience=5, restore_best_weights=True),
    ModelCheckpoint(os.path.join(MODEL_DIR, "garbage_classifier_best.keras"),
                     monitor="val_accuracy", save_best_only=True),
    ReduceLROnPlateau(monitor="val_loss", factor=0.5, patience=3, min_lr=1e-6),
]

EPOCHS = 15
history = model.fit(train_ds_p, validation_data=val_ds_p, epochs=EPOCHS, callbacks=callbacks)

base_model.trainable = True
FINE_TUNE_AT = len(base_model.layers) - 40
for layer in base_model.layers[:FINE_TUNE_AT]:
    layer.trainable = False

model.compile(optimizer=tf.keras.optimizers.Adam(1e-5),
              loss="categorical_crossentropy", metrics=["accuracy"])

FT_EPOCHS = 10
history_ft = model.fit(train_ds_p, validation_data=val_ds_p, epochs=FT_EPOCHS, callbacks=callbacks)

def combine_history(h1, h2, key):
    return h1.history[key] + h2.history[key]

acc = combine_history(history, history_ft, "accuracy")
val_acc = combine_history(history, history_ft, "val_accuracy")
loss = combine_history(history, history_ft, "loss")
val_loss = combine_history(history, history_ft, "val_loss")

