def predict_image(filepath, model, class_names, img_size=IMG_SIZE_TRAIN):
    img = cv2.imread(filepath)
    img = cv2.cvtColor(img, cv2.COLOR_BGR2RGB)
    img_resized = cv2.resize(img, img_size)
    img_arr = preprocess_input(np.expand_dims(img_resized.astype("float32"), axis=0))
    pred = model.predict(img_arr, verbose=0)[0]
    top_idx = np.argmax(pred)
    plt.imshow(img_resized)
    plt.axis("off")
    plt.title(f"Prediction: {class_names[top_idx]} ({pred[top_idx]*100:.1f}%)")
    plt.show()
    return class_names[top_idx], float(pred[top_idx])

